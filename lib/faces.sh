# shellcheck shell=bash
# faces.sh — Түбәтәйле татар йөзләре / Tatar faces in a tюбетейка (skullcap).
# Өч халәт: шат (уңыш), ачулы (хата), чәй (тәнәфес).
# Three moods: happy (success), angry (error), tea (break).

tat_face_happy() {
  cat >&2 <<'FACE'
        .:*~*:._.:*~*:.
      .'  ◆◇◆◇◆◇◆◇◆  '.      түбәтәй
     /___________________\
     |    ^         ^    |
     |         ᵕ         |
     |      \  ‿‿‿  /     |
      \_________________/
FACE
}

tat_face_angry() {
  cat >&2 <<'FACE'
        .:*~*:._.:*~*:.
      .'  ◆◇◆◇◆◇◆◇◆  '.      түбәтәй
     /___________________\
     |    ╲         ╱    |
     |     ◣       ◢     |
     |      ╱‾‾‾‾‾╲      |
      \_________________/
FACE
}

tat_face_tea() {
  cat >&2 <<'FACE'
        .:*~*:._.:*~*:.
      .'  ◆◇◆◇◆◇◆◇◆  '.      түбәтәй
     /___________________\
     |    -         -    |        ( (
     |         ‿         |         ) )
     |      \  ___  /     |       ........
      \_________________/        |      |]   сөтле чәй
                                 \      /
                                  `----'
FACE
}
